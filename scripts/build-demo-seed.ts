import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { buildDemoThread } from '../packages/core/src/demo-snapshot';
import { countClaims } from '../packages/core/src/claims';
import { norm } from '../packages/core/src/text';

// Generate a one-time D1 data migration through the shared parsing and threading rules.
// Stable IDs make reapplying these inserts safe without resetting public reports.
const base = Date.parse('2026-10-19T12:00:00+05:00');
const quote = (value: string | number | null) =>
  value === null
    ? 'NULL'
    : typeof value === 'number'
      ? String(value)
      : `'${value.replaceAll("'", "''")}'`;
const time = (value: number | null) =>
  value === null
    ? 'NULL'
    : `(CAST(strftime('%s','now') AS INTEGER)*1000-${base - value})`;
const lines = [
  '-- Generated by scripts/build-demo-seed.ts from existing simulated fixtures.',
];
for (const cluster of ['C01', 'C08', 'C05', 'C07', 'C10']) {
  const detail = buildDemoThread(cluster, base),
    i = detail.incident;
  const values = [
    i.id,
    'live',
    i.type,
    i.family,
    i.severity,
    i.status,
    i.areaId,
    i.lat,
    i.lng,
    i.summary,
    i.reportCount,
    JSON.stringify(countClaims(detail.reports)),
    JSON.stringify(i.languages),
  ].map(quote);
  lines.push(
    `INSERT OR IGNORE INTO incidents (id,ref,dataset,type,family,severity,status,area_id,lat,lng,summary,report_count,claim_counts,languages,first_seen,last_seen,escalated_at,created_at,updated_at,is_demo) VALUES (${values[0]},(SELECT COALESCE(MAX(ref),0)+1 FROM incidents WHERE dataset='live'),${values.slice(1).join(',')},${time(i.firstSeen)},${time(i.lastSeen)},${time(i.escalatedAt)},${time(i.firstSeen)},${time(i.updatedAt)},1);`,
  );
  for (const r of detail.reports) {
    if (!r.text) throw new Error('Demo report text is missing');
    const hash = createHash('sha256').update(norm(r.text)).digest('hex');
    const values = [
      r.id,
      i.id,
      'live',
      r.text,
      0,
      hash,
      r.language,
      r.type,
      r.severity,
      r.severityReason,
      r.areaId,
      r.locationText,
      r.lat,
      r.lng,
    ].map(quote);
    const rest = [
      r.timeText,
      r.summary,
      r.recommendedAction,
      JSON.stringify(r.claims),
      JSON.stringify(r.confidence),
      JSON.stringify(r.flags),
      r.engine,
      r.model,
    ].map(quote);
    lines.push(
      `INSERT OR IGNORE INTO reports (id,incident_id,dataset,text,text_hidden,text_hash,language,type,severity,severity_reason,area_id,location_text,lat,lng,occurred_at,time_text,summary,recommended_action,claims,confidence,flags,engine,model,created_at) VALUES (${values.join(',')},${time(r.occurredAt)},${rest.join(',')},${time(r.createdAt)});`,
    );
  }
  for (const e of detail.timeline) {
    const values = [
      e.kind,
      e.severity,
      e.reportId,
      e.fromType,
      e.toType,
      e.fromSeverity,
      e.toSeverity,
      e.fromStatus,
      e.toStatus,
    ].map(quote);
    lines.push(
      `INSERT INTO timeline_events (incident_id,at,kind,severity,report_id,from_type,to_type,from_severity,to_severity,from_status,to_status) SELECT ${quote(i.id)},${time(e.at)},${values.join(',')} WHERE NOT EXISTS (SELECT 1 FROM timeline_events WHERE incident_id=${quote(i.id)} AND report_id=${quote(e.reportId)} AND kind=${quote(e.kind)});`,
    );
  }
}
await writeFile(
  'apps/web/migrations/0003_demo_incidents.sql',
  lines.join('\n') + '\n',
);
process.stdout.write(
  'Generated five demo threads with eleven source reports.\n',
);
